// The five names kept for the Echoes (rule 25), compared by confusable
// skeleton (the owner's ruling on phase two's gate, Q4): the app tells people
// apart by name, so "Wаrden Echo" with a Cyrillic а is "Warden Echo". Unicode
// TR39's skeleton, for that fixed set only: NFD, each character replaced by its
// prototype, NFD again (https://www.unicode.org/reports/tr39/#Confusable_Detection).
// Keys from the name as typed and from its NFKC form (NFKC turns some
// look-alikes into letters with no Latin prototype: a lunate sigma ϲ becomes ς,
// the confirm pass's sweep), each taken two ways, from the name as given and
// lowercased first, and each settled: skeleton then lowercase, repeated until it
// stops changing. A name is a kept one if, character by character, one of
// each character's two settled forms spells a kept name's key, so a capital
// look-alike (a Greek Ε), every case of a kept name (a capital I's prototype is
// l: the final pass's F1), and both at once ("STRIKER ECH0", "ՏTRIKER ECHO": the
// confirm pass's C1 and its sweep) land on the kept name. Other names are
// compared as rule 4 says (nameKey), not by skeleton.
//
// The prototypes are in ./confusables-data.ts, generated by
// scripts/confusables.ts from TR39's confusables.txt and cut to the entries that
// can bear on these five names (the generator proves the cut changes no match).
import { KEPT_NAME_PROTOTYPES } from "./confusables-data.ts";

/** TR39's skeleton under a prototype table: NFD, each character its prototype, NFD. */
export function skeleton(s: string, prototypes: ReadonlyMap<string, string>): string {
  return [...s.normalize("NFD")].map((c) => prototypes.get(c) ?? c).join("").normalize("NFD");
}

/** Lowercase-after-skeleton, repeated until it stops changing: case and look-alikes folded together, in any order. */
function settle(s: string, prototypes: ReadonlyMap<string, string>): string {
  let x = s;
  for (let i = 0; i < 8; i++) {
    const next = skeleton(x, prototypes).toLowerCase();
    if (next === x) return x;
    x = next;
  }
  return x;
}

/**
 * A name's two keys against the kept Echo names: from the name as given, and
 * from it lowercased first, each settled (skeleton then lowercase, until it
 * stops changing). `s` has its invisibles gone. Settling folds a look-alike and
 * a case change in any order (the confirm pass's C1: "STRIKER ECH0", a capital I
 * beside a zero, slipped between two single passes).
 */
export function keptKeys(s: string, prototypes: ReadonlyMap<string, string> = KEPT_NAME_PROTOTYPES): [string, string] {
  return [settle(s, prototypes), settle(s.toLowerCase(), prototypes)];
}

/**
 * Whether `name` is the kept name `kept` or a look-alike of it in any case: some
 * choice, character by character, between each character's settled form as
 * given and lowercased spells one of the kept name's keys. A whole-name order
 * can't do it: "ՏTRIKER ECHO" needs the Armenian Տ taken as given (its prototype
 * is S) and the capital I lowercased (its prototype is l), both at once (the
 * confirm pass's sweep). Per character, each choice is one of the two keys the
 * generator cuts and proves.
 */
export function sameKept(name: string, kept: string, prototypes: ReadonlyMap<string, string> = KEPT_NAME_PROTOTYPES): boolean {
  const options = [...name].map((c) => [...new Set([settle(c, prototypes), settle(c.toLowerCase(), prototypes)])]);
  for (const target of new Set(keptKeys(kept, prototypes))) {
    let at = new Set([0]);
    for (const choices of options) {
      const next = new Set<number>();
      for (const i of at) for (const o of choices) if (target.startsWith(o, i)) next.add(i + o.length);
      at = next;
      if (at.size === 0) break;
    }
    if (at.has(target.length)) return true;
  }
  return false;
}
